import { mkdir, lstat, readlink, symlink, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const host = resolve(root, 'frontend/node_modules');
const withoutPlugin = process.argv.includes('--without-plugin');
for (const directory of [
  ...(withoutPlugin ? [] : ['plugins/ecotwin/frontend']),
  'distributions/symphony-ecotwin/frontend'
]) {
  const link = resolve(root, directory, 'node_modules');
  await lstat(host);
  await mkdir(resolve(root, directory), { recursive: true });
  try {
    const stat = await lstat(link);
    if (!stat.isSymbolicLink() || resolve(link, '..', await readlink(link)) !== host)
      throw new Error(`Refusing to replace ${link}; EcoTwin must share the host dependency tree.`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    await symlink(relative(resolve(link, '..'), host), link, 'dir');
  }
}

// Karma's source-root globbing does not reliably exclude an external symlinked
// dependency tree. Use one generated, exact entry containing only owned specs.
if (!withoutPlugin) {
  const plugin = resolve(root, 'plugins/ecotwin/frontend');
  async function specs(dir) {
    const files = [];
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      if (
        entry.name === 'node_modules' ||
        ['suite.spec.ts', 'core-suite.spec.ts'].includes(entry.name)
      )
        continue;
      const path = resolve(dir, entry.name);
      if (entry.isDirectory()) files.push(...(await specs(path)));
      else if (entry.name.endsWith('.spec.ts')) files.push(path);
    }
    return files;
  }
  await writeFile(
    resolve(plugin, 'suite.spec.ts'),
    '// Generated by the optional distribution test preparation.\n' +
      (await specs(plugin))
        .sort()
        .map((path) => `import './${relative(plugin, path).replaceAll('\\', '/').slice(0, -3)}';`)
        .join('\n') +
      '\n'
  );
  await writeFile(
    resolve(plugin, 'core-suite.spec.ts'),
    '// Generated: plugin tests with no Symphony source dependencies.\n' +
      (await specs(plugin))
        .filter((path) => !path.includes('/integration/'))
        .sort()
        .map((path) => `import './${relative(plugin, path).replaceAll('\\', '/').slice(0, -3)}';`)
        .join('\n') +
      '\n'
  );
}
